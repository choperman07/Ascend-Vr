        public static string Text(string key) { string s; return Lines.TryGetValue(key, out s) ? s : key; }

        /// <summary>Plays the line from a speaker and shows a subtitle above them for the clip length.</summary>
        public static float Say(string key, Transform speaker, float height = 2.15f, float volume = 1f)
        {
            if (Sfx.Clip(key) == null) return 0f;
            var src = speaker != null ? Sfx.Play(key, speaker.position + Vector3.up * 1.6f, volume) : Sfx.UI(key, volume);
            float dur = src != null && src.clip != null ? src.clip.length : 2f;
            if (speaker != null) Subtitle(speaker, Text(key), height, dur + 0.6f);
            return dur;
        }

        public static void Announce(string key, float volume = 0.9f) { if (Sfx.Clip(key) != null) Sfx.UI(key, volume); }

        static readonly Dictionary<Transform, TextMeshPro> subs = new Dictionary<Transform, TextMeshPro>();
        static readonly List<Transform> deadSubs = new List<Transform>();
        public static void Subtitle(Transform speaker, string text, float height, float seconds)
        {
            if (speaker == null) return;
            TextMeshPro tmp;
            if (!subs.TryGetValue(speaker, out tmp) || tmp == null)
            {
                // forget speakers that were destroyed (despawned guests, raid drones…) so the map doesn't grow forever
                deadSubs.Clear();
                foreach (var kv in subs) if (kv.Key == null || kv.Value == null) deadSubs.Add(kv.Key);
                foreach (var d in deadSubs) subs.Remove(d);
                tmp = Txt.Make("Subtitle", speaker, new Vector3(0, height, 0), "", 0.11f, Palette.Text, Palette.Body, TextAlignmentOptions.Center, 2.4f);
                tmp.gameObject.AddComponent<Billboard>();
                tmp.outlineWidth = 0.25f; tmp.outlineColor = new Color32(0, 0, 0, 200);
                subs[speaker] = tmp;
            }
            tmp.text = text;
            tmp.gameObject.SetActive(true);
            var hide = tmp.GetComponent<AutoHide>();
            if (hide == null) hide = tmp.gameObject.AddComponent<AutoHide>();
            hide.until = Time.time + seconds;
        }
    }
